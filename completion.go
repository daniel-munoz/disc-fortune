package main

import (
	"flag"
	"fmt"
	"sort"
	"strings"
)

// completionShells are the shells `completion` can generate for.
var completionShells = []string{"bash", "zsh", "fish"}

// flagValues holds the flags whose accepted values are compiled into the
// binary. Completing them costs nothing -- no file is read and no process is
// forked -- which is why they are here and collection-derived values such as
// --genre are not. TestCompletionEnumValuesAreAccepted pins each value to what
// the parser actually takes.
var flagValues = map[string][]string{
	"draw":  {"fresh", "any", "stale"},
	"color": {"auto", "always", "never"},
}

// completionFlag is one flag as completion needs to see it.
type completionFlag struct {
	name   string
	isBool bool     // a bool flag takes no value, so nothing follows it
	values []string // compiled-in values, if any
}

// commandFlagSet builds the FlagSet a command parses with, without parsing
// anything. Completion enumerates it and the parse functions register through
// the same add*Flags calls, so a flag added to one of those functions is
// offered for that command without anyone remembering to update a list.
//
// What that does NOT cover is a new *command*: the switch below is a second
// place to teach, and a command registering flags without a case here would
// silently offer only the globals. TestEveryCommandHasACompletionDecision is
// the forcing function for that, because no other test would fail.
func commandFlagSet(name string) *flag.FlagSet {
	// newFlagSet registers the global flags, so every command gets those
	// even when the switch below adds nothing.
	fs, _ := newFlagSet(name)
	switch name {
	case "pick", "list":
		addSelectionFlags(name, fs)
	case "history":
		addHistoryFlags(fs)
	case "favorite", "unfavorite":
		addFilterFlags(fs)
	case "sync":
		addSyncFlags(fs)
	}
	return fs
}

// commandFlags returns the flags a command accepts, sorted by name so the
// generated scripts are byte-stable between runs.
func commandFlags(name string) []completionFlag {
	var out []completionFlag
	commandFlagSet(name).VisitAll(func(f *flag.Flag) {
		out = append(out, completionFlag{
			name:   f.Name,
			isBool: isBoolFlag(f),
			values: flagValues[f.Name],
		})
	})
	sort.Slice(out, func(i, j int) bool { return out[i].name < out[j].name })
	return out
}

// isBoolFlag reports whether a flag is satisfied by its presence alone. The
// flag package marks these with an unexported interface that its own parser
// uses; asking the same question here keeps completion from suggesting a
// value where none is taken.
func isBoolFlag(f *flag.Flag) bool {
	bf, ok := f.Value.(interface{ IsBoolFlag() bool })
	return ok && bf.IsBoolFlag()
}

// parseCompletion validates completion's single argument, the shell name.
func parseCompletion(args []string) (string, error) {
	fs, _ := newFlagSet("completion")
	rest, err := parseInterspersed(fs, args)
	if err != nil {
		return "", fmt.Errorf("completion: %w", err)
	}
	if len(rest) == 0 {
		return "", fmt.Errorf("completion: requires a shell (%s)", strings.Join(completionShells, ", "))
	}
	if len(rest) > 1 {
		return "", fmt.Errorf("completion: too many arguments")
	}
	return rest[0], nil
}

// completionScript renders the completion script for one shell.
func completionScript(shell string) (string, error) {
	switch shell {
	case "bash":
		return bashCompletion(), nil
	case "zsh":
		return zshCompletion(), nil
	case "fish":
		return fishCompletion(), nil
	}
	return "", fmt.Errorf("unsupported shell %q (want %s)", shell, strings.Join(completionShells, ", "))
}

// shellQuote wraps a string for a single-quoted shell context. Command
// summaries are plain today, but a future one containing an apostrophe should
// not be able to break every user's completion.
func shellQuote(s string) string {
	return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'"
}

// flagNames renders a command's flags as the space-separated --name list the
// bash and zsh scripts complete from.
func flagNames(name string) string {
	flags := commandFlags(name)
	names := make([]string, len(flags))
	for i, f := range flags {
		names[i] = "--" + f.name
	}
	return strings.Join(names, " ")
}

func commandNames() []string {
	names := make([]string, len(commands))
	for i, c := range commands {
		names[i] = c.name
	}
	return names
}

func bashCompletion() string {
	var sb strings.Builder
	sb.WriteString(`# bash completion for disc-fortune. Generated by ` + "`disc-fortune completion bash`" + `.
# Load with: eval "$(disc-fortune completion bash)"

_disc_fortune() {
    local cur prev cmd i
    cur="${COMP_WORDS[COMP_CWORD]}"
    prev="${COMP_WORDS[COMP_CWORD-1]}"

    # The first non-flag word is the subcommand. There may be none: a leading
    # flag means the implicit pick command, which is why the fallback below
    # completes pick's flags rather than only the global ones.
    cmd=""
    for ((i = 1; i < COMP_CWORD; i++)); do
        case "${COMP_WORDS[i]}" in
            -*) ;;
            *) cmd="${COMP_WORDS[i]}"; break ;;
        esac
    done

    # A flag that takes one of a fixed set of values.
    case "$prev" in
`)
	for _, name := range sortedKeys(flagValues) {
		fmt.Fprintf(&sb, "        --%s)\n            COMPREPLY=( $(compgen -W %s -- \"$cur\") )\n            return\n            ;;\n",
			name, shellQuote(strings.Join(flagValues[name], " ")))
	}
	sb.WriteString(`    esac

    if [[ "$cur" == -* ]]; then
        case "$cmd" in
`)
	for _, c := range commands {
		fmt.Fprintf(&sb, "            %s)\n                COMPREPLY=( $(compgen -W %s -- \"$cur\") )\n                ;;\n",
			c.name, shellQuote(flagNames(c.name)))
	}
	fmt.Fprintf(&sb, `            *)
                COMPREPLY=( $(compgen -W %s -- "$cur") )
                ;;
        esac
        return
    fi

    if [[ -z "$cmd" ]]; then
        COMPREPLY=( $(compgen -W %s -- "$cur") )
    fi
}

complete -F _disc_fortune disc-fortune
`, shellQuote(flagNames("pick")), shellQuote(strings.Join(commandNames(), " ")))

	return sb.String()
}

func zshCompletion() string {
	var sb strings.Builder
	sb.WriteString(`#compdef disc-fortune
# zsh completion for disc-fortune. Generated by ` + "`disc-fortune completion zsh`" + `.
# Load with: eval "$(disc-fortune completion zsh)"

_disc_fortune() {
    local -a subcommands
    subcommands=(
`)
	for _, c := range commands {
		// _describe takes name:description pairs, so a colon inside a
		// description would split it in the wrong place.
		desc := strings.ReplaceAll(c.summary, ":", `\:`)
		fmt.Fprintf(&sb, "        %s\n", shellQuote(c.name+":"+desc))
	}
	sb.WriteString(`    )

    local cmd="" i
    for (( i = 2; i < CURRENT; i++ )); do
        case ${words[i]} in
            -*) ;;
            *) cmd=${words[i]}; break ;;
        esac
    done

    case ${words[CURRENT-1]} in
`)
	for _, name := range sortedKeys(flagValues) {
		fmt.Fprintf(&sb, "        --%s)\n            _values %s %s\n            return\n            ;;\n",
			name, shellQuote(name), strings.Join(flagValues[name], " "))
	}
	sb.WriteString(`    esac

    if [[ ${words[CURRENT]} == -* ]]; then
        local -a flags
        case $cmd in
`)
	for _, c := range commands {
		fmt.Fprintf(&sb, "            %s) flags=(%s) ;;\n", c.name, flagNames(c.name))
	}
	fmt.Fprintf(&sb, `            *) flags=(%s) ;;
        esac
        compadd -- $flags
        return
    fi

    if [[ -z $cmd ]]; then
        _describe 'command' subcommands
    fi
}

# Sourced (eval) this registers the function; autoloaded from fpath, zsh calls
# the file *as* the completion function, so it must run rather than re-register.
if [ "$funcstack[1]" = "_disc_fortune" ]; then
    _disc_fortune "$@"
else
    compdef _disc_fortune disc-fortune
fi
`, flagNames("pick"))

	return sb.String()
}

// fishValueSpec renders what fish should offer after a flag.
//
// -x is load-bearing: -r means only "this option takes an argument" and leaves
// fish's default filename completion in place, so `--genre <TAB>` offered the
// working directory. The file-scoped `complete -c disc-fortune -f` does not
// reach an option's argument. -x is -r plus "offer nothing else".
func fishValueSpec(f completionFlag) string {
	switch {
	case len(f.values) > 0:
		return " -x -a " + shellQuote(strings.Join(f.values, " "))
	case !f.isBool:
		return " -x"
	}
	return ""
}

func fishCompletion() string {
	var sb strings.Builder
	sb.WriteString("# fish completion for disc-fortune. Generated by `disc-fortune completion fish`.\n")
	sb.WriteString("# Load with: disc-fortune completion fish | source\n\n")

	// disc-fortune takes no file arguments, so fish's default filename
	// completion is never right: without this, tab on a bare `disc-fortune `
	// lists the current directory instead of the subcommands.
	sb.WriteString("# No argument of any command is a path.\ncomplete -c disc-fortune -f\n\n")

	sb.WriteString("# Subcommands, offered only in the first position.\n")
	for _, c := range commands {
		fmt.Fprintf(&sb, "complete -c disc-fortune -n __fish_use_subcommand -a %s -d %s\n",
			shellQuote(c.name), shellQuote(c.summary))
	}

	sb.WriteString("\n# Flags, scoped to the commands that accept them.\n")
	for _, c := range commands {
		for _, f := range commandFlags(c.name) {
			fmt.Fprintf(&sb, "complete -c disc-fortune -n %s -l %s%s\n",
				shellQuote("__fish_seen_subcommand_from "+c.name), f.name, fishValueSpec(f))
		}
	}

	// A bare `disc-fortune --genre jazz` is a pick: resolve treats a leading
	// flag as the default command. So the no-subcommand position takes pick's
	// flags, not merely the global ones.
	sb.WriteString("\n# Before a subcommand is typed, a flag means the implicit `pick`.\n")
	for _, f := range commandFlags("pick") {
		fmt.Fprintf(&sb, "complete -c disc-fortune -n __fish_use_subcommand -l %s%s\n",
			f.name, fishValueSpec(f))
	}

	return sb.String()
}

// sortedKeys keeps generated output byte-stable: Go's map iteration order is
// deliberately random, and a script that differs between runs would show up as
// spurious diffs for anyone checking one in.
func sortedKeys(m map[string][]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func runCompletion(shell string) {
	script, err := completionScript(shell)
	if err != nil {
		fatal("Error: %v", err)
	}
	fmt.Print(script)
}
